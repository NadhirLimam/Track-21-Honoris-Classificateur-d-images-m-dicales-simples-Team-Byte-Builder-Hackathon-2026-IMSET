// src/components/prediction/ExplanationCard.jsx
import { motion } from 'framer-motion'
import { AlertTriangle, Sparkles } from 'lucide-react'

/**
 * ExplanationCard — displays the Gemini AI text explanation + probability bars.
 * Props:
 *   explanation    : string  — returned by Gemini (or fallback)
 *   probabilities  : { normal: number, review: number }  — 0-100 percentages
 */
export default function ExplanationCard({ explanation, probabilities }) {
  const normal = probabilities?.normal ?? 0
  const review = probabilities?.review ?? 0

  return (
    <motion.div
      initial={{ opacity: 0, y: 16 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.45, ease: 'easeOut' }}
      className="rounded-xl border border-[#1E2D45] bg-[#0F1623] overflow-hidden"
      style={{ borderLeft: '3px solid #0A84FF' }}
    >
      {/* Header */}
      <div className="flex items-center justify-between px-5 pt-4 pb-3 border-b border-[#1E2D45]">
        <div className="flex items-center gap-2">
          <div className="h-7 w-7 rounded-lg bg-[rgba(10,132,255,0.12)] flex items-center justify-center">
            <Sparkles size={14} className="text-primary" />
          </div>
          <span className="text-sm font-semibold text-[#E8F0FF]">Gemini Analysis</span>
        </div>

        {/* Google Gemini badge */}
        <span
          className="px-2.5 py-1 rounded-full text-[10px] font-semibold tracking-wide"
          style={{
            background: 'linear-gradient(135deg, rgba(10,132,255,0.15), rgba(167,139,250,0.15))',
            border: '1px solid rgba(10,132,255,0.25)',
            color: '#A78BFA',
          }}
        >
          Google Gemini
        </span>
      </div>

      <div className="px-5 py-4 space-y-5">
        {/* Explanation text */}
        <blockquote
          className="text-sm leading-relaxed text-[#7A90B0] italic"
          style={{ borderLeft: 'none' }}
        >
          "{explanation || 'No explanation available.'}"
        </blockquote>

        {/* Probability bars */}
        <div className="space-y-2.5">
          <ProbBar label="Normal" value={normal} color="#34D399" />
          <ProbBar label="À vérifier" value={review} color="#FB923C" />
        </div>

        {/* Disclaimer */}
        <div className="flex items-start gap-2 p-3 rounded-lg bg-[rgba(251,146,60,0.06)] border border-[rgba(251,146,60,0.15)]">
          <AlertTriangle size={12} className="text-[#FB923C] mt-0.5 shrink-0" />
          <p className="text-[10px] leading-relaxed text-[#7A90B0]">
            Educational simulation — results generated by Gemini AI for demonstration purposes only
            and have <strong className="text-[#FB923C]">no medical validity</strong>.
          </p>
        </div>
      </div>
    </motion.div>
  )
}

function ProbBar({ label, value, color }) {
  return (
    <div className="space-y-1">
      <div className="flex justify-between text-xs">
        <span className="text-[#7A90B0]">{label}</span>
        <span className="font-mono font-semibold" style={{ color }}>
          {typeof value === 'number' ? value.toFixed(1) : '—'}%
        </span>
      </div>
      <div className="h-1.5 rounded-full bg-[#161F30] overflow-hidden">
        <motion.div
          initial={{ width: 0 }}
          animate={{ width: `${Math.min(value, 100)}%` }}
          transition={{ duration: 1.1, ease: 'easeOut' }}
          className="h-full rounded-full"
          style={{ background: color }}
        />
      </div>
    </div>
  )
}
